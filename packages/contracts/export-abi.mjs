import { readFileSync, writeFileSync } from "node:fs";
const read = (n) => JSON.parse(readFileSync(new URL(`./out/${n}.sol/${n}.json`, import.meta.url)));
const L = read("CalibrationLedger"), P = read("AgentPolicy");
const out = `// Generated by packages/contracts/export-abi.mjs from forge build output. Do not edit.
export const calibrationLedgerAbi = ${JSON.stringify(L.abi, null, 2)} as const;
export const agentPolicyAbi = ${JSON.stringify(P.abi, null, 2)} as const;
export const calibrationLedgerBytecode = ${JSON.stringify(L.bytecode.object)} as const;
export const agentPolicyBytecode = ${JSON.stringify(P.bytecode.object)} as const;
`;
writeFileSync(new URL("../shared/src/abi.ts", import.meta.url), out);
console.log("wrote packages/shared/src/abi.ts");
